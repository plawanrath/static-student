F32 = np.float32


class Blob:
    """The byte stream of `SS_W[]`, built in the kernel's reading order; every append returns its offset."""

    def __init__(self) -> None:
        self.buf = bytearray()
        self.names: list[tuple[str, int, int]] = []

    def add(self, name: str, data: bytes, align: int = 4) -> int:
        while len(self.buf) % align:
            self.buf.append(0)
        off = len(self.buf)
        self.buf += data
        self.names.append((name, off, len(data)))
        return off

    def f32(self, name: str, a: np.ndarray) -> int:
        return self.add(name, np.ascontiguousarray(a, dtype="<f4").tobytes())

    def f16(self, name: str, a: np.ndarray) -> int:
        return self.add(name, np.ascontiguousarray(a, dtype="<f2").tobytes(), align=2)

    def i8(self, name: str, a: np.ndarray) -> int:
        lo, hi = int(np.min(a)), int(np.max(a))
        if lo < -128 or hi > 127:
            raise ValueError(f"{name}: levels span [{lo}, {hi}], which does not fit one byte; the kernel reads int8 rows")
        return self.add(name, np.ascontiguousarray(a, dtype="<i1").tobytes(), align=1)

    def packed_levels(self, name: str, levels: np.ndarray, bits: int) -> int:
        """Levels at `bits` each, LSB first, one whole number of bytes per group of 32 (8, 12 or 16 bytes)."""
        out, per_group = bytearray(), GROUP * bits // 8
        assert GROUP * bits % 8 == 0
        flat = (levels.astype(np.int32) & ((1 << bits) - 1)).reshape(-1, GROUP)
        for row in flat:
            acc, nbits, chunk = 0, 0, bytearray()
            for v in row:
                acc |= int(v) << nbits
                nbits += bits
                while nbits >= 8:
                    chunk.append(acc & 0xFF)
                    acc >>= 8
                    nbits -= 8
            assert nbits == 0 and len(chunk) == per_group
            out += chunk
        return self.add(name, bytes(out), align=1)


def _c_array(data: bytes, per_line: int = 24) -> str:
    lines = [", ".join(f"0x{b:02x}" for b in data[i:i + per_line]) for i in range(0, len(data), per_line)]
    return ",\n  ".join(lines)


def build_blob(p: Packed) -> tuple[Blob, dict]:
    b, off = Blob(), {}
    off["tok_levels"], off["tok_scale"] = b.i8("tok.levels", p.tok.levels), b.f32("tok.scale", p.tok.scale)
    off["pos_levels"], off["pos_scale"] = b.i8("pos.levels", p.pos.levels), b.f32("pos.scale", p.pos.scale)
    off["ln_in_w"], off["ln_in_b"] = b.f32("ln_in.weight", p.ln_in[0]), b.f32("ln_in.bias", p.ln_in[1])
    for i, blk in enumerate(p.blocks):
        for name in ("q", "k", "v", "o", "up", "down"):
            l: QuantLinear = blk[name]
            off[f"b{i}_{name}_lv"] = b.packed_levels(f"b{i}.{name}.levels", l.levels, p.bits)
            off[f"b{i}_{name}_sc"] = b.f16(f"b{i}.{name}.scales", l.scales)
            off[f"b{i}_{name}_bi"] = b.f32(f"b{i}.{name}.bias", l.bias)
        for ln in ("ln1", "ln2"):
            off[f"b{i}_{ln}_w"] = b.f32(f"b{i}.{ln}.weight", blk[ln][0])
            off[f"b{i}_{ln}_b"] = b.f32(f"b{i}.{ln}.bias", blk[ln][1])
    for name, r in (("ptr", p.pointers), ("unit", p.unit), ("defer", p.defer)):
        off[f"{name}_levels"] = b.i8(f"{name}.levels", r.levels)
        off[f"{name}_scale"] = b.f32(f"{name}.scale", r.scale)
        off[f"{name}_bias"] = b.f32(f"{name}.bias", r.bias)
    return b, off


