"""Emit the constant weight array and the C kernel that reads it.

`emit(packed, out_dir)` writes three files and nothing else:

  ss_weights.c   one `const unsigned char SS_W[]`, aligned, in its own section, holding every tensor in the order the
                 kernel walks it: trunk levels packed at the trained bit width, group scales as float16, biases and
                 LayerNorm parameters as float32, embeddings and head matrices as int8 rows with one float32 scale.
  ss_kernel.h    the shapes, the offsets into `SS_W[]`, and the two entry points.
  ss_kernel.c    a transliteration of `oracle.py`: the same algorithm, the same constants, the same order of
                 operations, so that the two agree bit for bit (gate G1a).

The kernel allocates nothing: the caller supplies a scratch buffer whose size is a compile-time constant.
"""
