def emit(p: Packed, out_dir: str | Path, section: str | None = None) -> dict:
    out = Path(out_dir)
    out.mkdir(parents=True, exist_ok=True)
    blob, off = build_blob(p)
    cfg = p.config
    d, heads = cfg["d_model"], cfg["heads"]
    head_dim, ffn = d // heads, cfg["ffn_mult"] * d
    inv = float(inv_sqrt_head_dim(head_dim))  # exactly the reference's expression: divide in double, round once.
    # Rounding the square root to float32 first and then dividing differs by one unit in the last place at
    # head_dim 24, which was enough to break bit-exactness for the XS student while leaving S unaffected.

    header = HEADER.format(layers=cfg["layers"], d=d, heads=heads, head_dim=head_dim, ffn=ffn, max_len=MAX_LEN,
                           bits=p.bits, group=GROUP, vocab=p.tok.levels.shape[0], pad=PAD, cls=CLS,
                           n_ptr=len(POINTERS), n_unit=len(UNIT_CLASSES), nbytes=len(blob.buf))
    defines = [f"#define SS_INV_SQRT_HEAD_DIM {inv:.9g}f"]
    for key in ("tok_levels", "tok_scale", "pos_levels", "pos_scale", "ln_in_w", "ln_in_b",
                "ptr_levels", "ptr_scale", "ptr_bias", "unit_levels", "unit_scale", "unit_bias",
                "defer_levels", "defer_scale", "defer_bias"):
        defines.append(f"#define SS_OFF_{key.upper()} {off[key]}u")
    rows = []
    for i in range(cfg["layers"]):
        g = lambda k: off[f"b{i}_{k}"]  # noqa: E731
        rows.append("  { {%s}, {%s}, {%s}, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d, %d }," % (
            ", ".join(f"{g(f'{x}_lv')}u" for x in "qkv"), ", ".join(f"{g(f'{x}_sc')}u" for x in "qkv"),
            ", ".join(f"{g(f'{x}_bi')}u" for x in "qkv"),
            g("o_lv"), g("o_sc"), g("o_bi"), g("up_lv"), g("up_sc"), g("up_bi"), g("down_lv"), g("down_sc"), g("down_bi"),
            g("ln1_w"), g("ln1_b"), g("ln2_w"), g("ln2_b")))
    header = header.replace("extern const unsigned char SS_W",
                            "\n".join(defines) + "\n" + LAYER_STRUCT.replace("{rows}", "\n".join(rows)) + "\nextern const unsigned char SS_W")
    (out / "ss_kernel.h").write_text(header)

    attr = f'__attribute__((aligned(64), section("{section}")))' if section else "__attribute__((aligned(64)))"
    (out / "ss_weights.c").write_text(
        "/* Generated by static_student.codegen.emit. Do not edit. */\n#include \"ss_kernel.h\"\n\n"
        f"/* {len(blob.buf)} bytes: the whole model, as read-only program data. */\n"
        f"{attr}\nconst unsigned char SS_W[SS_WEIGHT_BYTES] = {{\n  " + _c_array(bytes(blob.buf)) + "\n};\n")
    (out / "ss_kernel.c").write_text(KERNEL)
    manifest = {**p.manifest(), "weight_bytes": len(blob.buf), "sections": [{"name": n, "offset": o, "bytes": ln} for n, o, ln in blob.names],
                "scratch_bytes": 4 * (MAX_LEN * d + MAX_LEN * ffn + 3 * MAX_LEN * d + MAX_LEN + MAX_LEN * d + MAX_LEN + ffn * d // GROUP) + MAX_LEN * ffn + ffn * d}
    (out / "manifest.json").write_text(__import__("json").dumps(manifest, indent=1) + "\n")
    return manifest
