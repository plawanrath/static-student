"""Emit a native kernel for an imported ModernBERT classifier: weights as a linked constant, C that matches the reference.

Output directory contents:
  mb_weights.bin   every tensor the kernel reads, in the shipped precision, 64-byte aligned
  mb_weights.S     places mb_weights.bin in a read-only section under the symbol `mb_W` (assembler `.incbin`, so a
                   400 MB constant never passes through a C compiler as text)
  mb_model.h       dimensions, layer types, and the byte offset of every tensor inside mb_W
  mb_kernel.c      the forward pass (fixed source; only the header changes between models)
  mb_cli.c         line driver: token ids in, "<label> <prob> <logit...>" out, floats as exact hex
Every floating-point operation is performed in the order `modernbert.forward` performs it, so the outputs are
bit-identical to the reference on any IEEE-754 machine that honours -ffp-contract=off. Integer dot products may be
vectorized freely, because an exact integer sum does not depend on its order.
"""
