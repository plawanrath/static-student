ALIGN = 64


class Blob:
    def __init__(self):
        self.parts, self.size, self.off = [], 0, {}

    def add(self, name: str, a: np.ndarray) -> int:
        pad = (-self.size) % ALIGN
        if pad:
            self.parts.append(b"\0" * pad)
            self.size += pad
        b = np.ascontiguousarray(a).tobytes()
        self.off[name] = self.size
        self.parts.append(b)
        self.size += len(b)
        return self.off[name]


def _f32(a):
    return np.asarray(a, dtype=np.float32)


def pack_levels(levels: np.ndarray, bits: int) -> np.ndarray:
    """Row-major levels in the shipped width: one per byte at 8 bits, two per byte at 4 bits (low nibble first)."""
    if bits == 8:
        return levels.astype(np.int8)
    assert bits == 4 and levels.shape[-1] % 2 == 0 and levels.min() >= -8 and levels.max() <= 7
    nib = (levels.astype(np.int16) & 0xF).astype(np.uint8)
    return (nib[..., 0::2] | (nib[..., 1::2] << 4)).astype(np.uint8)


def build_blob(p: MBPacked) -> tuple[bytes, dict]:
    b = Blob()
    b.add("tok_levels", p.tok.levels.astype(np.int8))
    b.add("tok_scale", _f32(p.tok.scale))
    b.add("emb_norm", _f32(p.emb_norm))
    for i, L in enumerate(p.layers):
        if L["attn_norm"] is not None:
            b.add(f"l{i}_attn_norm", _f32(L["attn_norm"]))
        b.add(f"l{i}_mlp_norm", _f32(L["mlp_norm"]))
        for k in ("qkv", "o", "wi", "wo"):
            b.add(f"l{i}_{k}_levels", pack_levels(L[k].levels, p.bits))
            b.add(f"l{i}_{k}_scales", _f32(L[k].scales))
    b.add("final_norm", _f32(p.final_norm))
    b.add("head_levels", pack_levels(p.head_dense.levels, p.bits))
    b.add("head_scales", _f32(p.head_dense.scales))
    b.add("head_norm", _f32(p.head_norm))
    b.add("cls_levels", p.cls.levels.astype(np.int8))
    b.add("cls_scale", _f32(p.cls.scale))
    b.add("cls_bias", _f32(p.cls_bias))
    for t in ("full_attention", "sliding_attention"):
        cos, sin = p.rope[t]
        b.add(f"rope_{t}_cos", _f32(cos))
        b.add(f"rope_{t}_sin", _f32(sin))
    return b"".join(b.parts), b.off


